#include <stdio.h>
#include <math.h>

#define SAMPLES 2000
#define FS 250
#define THRESHOLD_FACTOR 0.70f
#define MIN_RR_SECONDS 0.35f
#define MIN_RR_SAMPLES ((int)(MIN_RR_SECONDS * FS))
#define HALF_WINDOW (MIN_RR_SAMPLES / 2)
#define MAX_PEAKS 50

typedef struct {
    int index[SAMPLES];
    int front;
    int rear;
} Deque;

static void deque_init(Deque *dq) { dq->front = 0; dq->rear = -1; }
static int deque_empty(const Deque *dq) { return dq->front > dq->rear; }
static void pop_front(Deque *dq) { if (!deque_empty(dq)) dq->front++; }
static void pop_back(Deque *dq) { if (!deque_empty(dq)) dq->rear--; }
static void push_back(Deque *dq, int index) { dq->index[++dq->rear] = index; }
static int front_index(const Deque *dq) { return deque_empty(dq) ? -1 : dq->index[dq->front]; }

int main(void)
{
    float max_value = ecg[0];
    float min_value = ecg[0];

    for (int i = 1; i < SAMPLES; ++i) {
        if (ecg[i] > max_value) max_value = ecg[i];
        if (ecg[i] < min_value) min_value = ecg[i];
    }

    float threshold = THRESHOLD_FACTOR * max_value;

    printf("Samples       : %d\n", SAMPLES);
    printf("Sampling rate : %d Hz\n", FS);
    printf("Min value     : %.6f\n", min_value);
    printf("Max value     : %.6f\n", max_value);
    printf("Threshold     : %.6f\n", threshold);
    printf("Min RR        : %.2f s (%d samples)\n\n", MIN_RR_SECONDS, MIN_RR_SAMPLES);

    Deque dq;
    deque_init(&dq);

    int peaks[MAX_PEAKS];
    int peak_count = 0;

    /*
       Centered sliding-window maximum using a monotonic deque.
       A sample becomes a peak candidate only after HALF_WINDOW
       samples have arrived on its right side.
    */
    for (int i = 0; i < SAMPLES; ++i) {
        while (!deque_empty(&dq) &&
               front_index(&dq) < i - MIN_RR_SAMPLES + 1) {
            pop_front(&dq);
        }

        /* Keep only samples that can cross the amplitude threshold. */
        if (ecg[i] >= threshold) {
            while (!deque_empty(&dq) &&
                   ecg[dq.index[dq.rear]] <= ecg[i]) {
                pop_back(&dq);
            }
            push_back(&dq, i);
        }

        if (i >= MIN_RR_SAMPLES - 1) {
            int center = i - HALF_WINDOW;

            while (!deque_empty(&dq) &&
                   front_index(&dq) < center - HALF_WINDOW) {
                pop_front(&dq);
            }

            if (!deque_empty(&dq) &&
                front_index(&dq) == center) {

                if (peak_count == 0 ||
                    center - peaks[peak_count - 1] >= MIN_RR_SAMPLES) {
                    if (peak_count < MAX_PEAKS) {
                        peaks[peak_count++] = center;
                    }
                }
            }
        }
    }

    printf("Detected R peaks: %d\n\n", peak_count);

    float rr_sum = 0.0f;

    for (int i = 0; i < peak_count; ++i) {
        printf("R%-2d: sample=%4d  time=%.3f s  value=%+.6f",
               i + 1, peaks[i], (float)peaks[i] / FS, ecg[peaks[i]]);

        if (i > 0) {
            float rr = (float)(peaks[i] - peaks[i - 1]) / FS;
            float bpm = 60.0f / rr;
            rr_sum += rr;
            printf("  RR=%.3f s  BPM=%.2f", rr, bpm);
        }

        printf("\n");
    }

    if (peak_count >= 2) {
        float avg_rr = rr_sum / (peak_count - 1);
        float avg_bpm = 60.0f / avg_rr;

        printf("\nAverage RR  = %.4f s\n", avg_rr);
        printf("Average BPM = %.2f\n", avg_bpm);
    } else {
        printf("\nNot enough peaks to calculate RR/BPM.\n");
    }

    return 0;
}
